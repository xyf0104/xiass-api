import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import WeekendDiscountDialog from '../WeekendDiscountDialog.vue'

const { getWeekendDiscount, saveWeekendDiscount, showSuccess } = vi.hoisted(() => ({ getWeekendDiscount: vi.fn(), saveWeekendDiscount: vi.fn(), showSuccess: vi.fn() }))
vi.mock('@/api/weekendDiscount', () => ({ getWeekendDiscount, saveWeekendDiscount }))
vi.mock('@/stores/app', () => ({ useAppStore: () => ({ showSuccess }) }))

function render() { return mount(WeekendDiscountDialog, { global: { stubs: { BaseDialog: { template: '<section><slot /></section>' } } } }) }

describe('WeekendDiscountDialog', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    getWeekendDiscount.mockResolvedValue({ enabled: false, starts_at: null, ends_at: null, server_time: '2026-11-20T12:00:00+08:00' })
    saveWeekendDiscount.mockResolvedValue({ enabled: true, active: false })
  })
  it('saves Beijing schedule and switch independently of the local timezone', async () => {
    const wrapper = render()
    await flushPromises()
    await wrapper.get('#weekend-enabled').setValue(true)
    await wrapper.get('#weekend-start').setValue('2026-11-21T00:00')
    await wrapper.get('#weekend-end').setValue('2026-12-01T00:00')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(saveWeekendDiscount).toHaveBeenCalledWith({ enabled: true, mode: 'weekends', starts_at: '2026-11-20T16:00:00.000Z', ends_at: '2026-11-30T16:00:00.000Z' })
    expect(showSuccess).toHaveBeenCalledOnce()
    await wrapper.get('#weekend-enabled').setValue(false)
    await wrapper.get('form').trigger('submit')
    expect(saveWeekendDiscount.mock.lastCall?.[0].enabled).toBe(false)
    wrapper.unmount()
  })
  it('saves a custom weekday interval and restores the selected mode', async () => {
    getWeekendDiscount.mockResolvedValueOnce({ enabled: true, mode: 'custom', starts_at: '2026-11-20T12:00:00+08:00', ends_at: null })
    const wrapper = render()
    await flushPromises()
    expect((wrapper.get('input[value="custom"]').element as HTMLInputElement).checked).toBe(true)
    expect(wrapper.get('#weekend-start').element).toHaveProperty('value', '2026-11-20T12:00')
    await wrapper.get('#weekend-end').setValue('2026-11-20T18:00')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(saveWeekendDiscount).toHaveBeenCalledWith({ enabled: true, mode: 'custom', starts_at: '2026-11-20T04:00:00.000Z', ends_at: '2026-11-20T10:00:00.000Z' })
    wrapper.unmount()
  })
  it('starts immediately using the server clock and replaces the future weekend start', async () => {
    const serverTime = '2026-11-20T12:00:19+08:00'
    const wrapper = render()
    await flushPromises()
    await wrapper.get('#weekend-start').setValue('2026-11-21T00:00')
    await wrapper.get('#weekend-end').setValue('2026-11-20T18:00')
    getWeekendDiscount.mockResolvedValueOnce({ server_time: serverTime })
    saveWeekendDiscount.mockResolvedValueOnce({ enabled: true, mode: 'custom', active: true, starts_at: serverTime, ends_at: '2026-11-20T10:00:00.000Z' })
    await wrapper.findAll('button').find(button => button.text() === '现在开始')!.trigger('click')
    await flushPromises()
    expect(saveWeekendDiscount).toHaveBeenCalledWith({ enabled: true, mode: 'custom', starts_at: serverTime, ends_at: '2026-11-20T10:00:00.000Z' })
    expect(wrapper.text()).toContain('已保存状态：八折生效中')
    expect((wrapper.get('input[value="custom"]').element as HTMLInputElement).checked).toBe(true)
    expect(wrapper.get('#weekend-enabled').element).toHaveProperty('checked', true)
    expect(showSuccess).toHaveBeenCalledWith('八折活动已立即开启')
    wrapper.unmount()
  })
  it('rejects a past end when starting now', async () => {
    const wrapper = render()
    await flushPromises()
    await wrapper.get('#weekend-end').setValue('2026-11-20T11:59')
    await wrapper.findAll('button').find(button => button.text() === '现在开始')!.trigger('click')
    await flushPromises()
    expect(saveWeekendDiscount).not.toHaveBeenCalled()
    expect(wrapper.get('[role="alert"]').text()).toContain('结束时间已过')
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })
  it('does not show an active promotion if starting now fails', async () => {
    saveWeekendDiscount.mockRejectedValueOnce(new Error('offline'))
    const wrapper = render()
    await flushPromises()
    await wrapper.findAll('button').find(button => button.text() === '现在开始')!.trigger('click')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBeTruthy()
    expect(wrapper.get('#weekend-enabled').element).toHaveProperty('checked', false)
    expect((wrapper.get('input[value="weekends"]').element as HTMLInputElement).checked).toBe(true)
    expect(showSuccess).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('rejects an inverted range before sending a save', async () => {
    const wrapper = render()
    await flushPromises()
    await wrapper.get('#weekend-start').setValue('2026-11-22T00:00')
    await wrapper.get('#weekend-end').setValue('2026-11-21T00:00')
    await wrapper.get('form').trigger('submit')
    expect(saveWeekendDiscount).not.toHaveBeenCalled()
    expect(wrapper.get('[role="alert"]').text()).toContain('结束时间必须晚于开始时间')
    wrapper.unmount()
  })
  it('does not overwrite saved settings when loading fails', async () => {
    getWeekendDiscount.mockRejectedValueOnce(new Error('offline'))
    const wrapper = render()
    await flushPromises()
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    expect(wrapper.get('[role="alert"]').text()).toBeTruthy()
    expect(saveWeekendDiscount).not.toHaveBeenCalled()
    wrapper.unmount()
  })
})
