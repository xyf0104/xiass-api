package handler

import (
	"context"
	"testing"

	"github.com/Wei-Shaw/sub2api/internal/pkg/ctxkey"
	"github.com/Wei-Shaw/sub2api/internal/service"
	"github.com/stretchr/testify/require"
)

func TestSubmitUsageRecordTaskCopiesRequestContext(t *testing.T) {
	parent := context.WithValue(context.Background(), ctxkey.ClientRequestID, "client-request-123")
	parent = context.WithValue(parent, ctxkey.RequestID, "request-456")

	var gotClientRequestID string
	var gotRequestID string
	h := &GatewayHandler{}
	h.submitUsageRecordTask(parent, func(ctx context.Context) {
		gotClientRequestID, _ = ctx.Value(ctxkey.ClientRequestID).(string)
		gotRequestID, _ = ctx.Value(ctxkey.RequestID).(string)
	})

	require.Equal(t, "client-request-123", gotClientRequestID)
	require.Equal(t, "request-456", gotRequestID)
}

func TestUsageRecordTaskCopiesEgressBeforeAsyncDispatch(t *testing.T) {
	account := &service.Account{ID: 12, RequestProxy: &service.Proxy{ID: 23, Name: "selected", Protocol: "http", Host: "proxy.test", Port: 3128}}
	parent := service.UsageEgressContext(context.Background(), nil, account)
	var recorded *service.UsageEgress
	task := wrapUsageRecordTaskContext(parent, func(ctx context.Context) {
		recorded = service.UsageEgressFromContext(ctx)
	})
	account.RequestProxy.ID = 99
	account.RequestProxy.Name = "next request"
	task(context.Background())
	require.Equal(t, int64(23), recorded.ProxyID)
	require.Equal(t, "selected", recorded.ProxyName)
}

